const SUPPORTED_LANGS = ["en", "pt"];
const DEFAULT_LANG = "en";

function getLang() {
  const stored = localStorage.getItem("ct_lang");
  return SUPPORTED_LANGS.includes(stored) ? stored : DEFAULT_LANG;
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  localStorage.setItem("ct_lang", lang);
}

// t(key, vars?) -> translated string with optional {placeholder} interpolation
function t(key, vars) {
  const lang = getLang();
  let str = (I18N[lang] && I18N[lang][key]) || I18N[DEFAULT_LANG][key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp(`{${k}}`, "g"), vars[k]);
    });
  }
  return str;
}
